'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const {execFileSync} = require('node:child_process');
const dir = __dirname;
const manifestDoc = fs.readFileSync(path.join(dir, 'appsscript.json.md'), 'utf8');
const markdown = fs.readFileSync(path.join(dir, 'Agenda.html.md'), 'utf8');
const guide = fs.readFileSync(path.join(dir, 'PUBLICAR-SOLO-APPS-SCRIPT.md'), 'utf8');
const readme = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
const render = fs.readFileSync(path.join(dir, 'Render.gs'), 'utf8');
const backendPath = path.join(dir, '..', 'Code.gs');
const backend = fs.readFileSync(backendPath, 'utf8');
assert.equal(fs.existsSync(path.join(dir, 'Code.gs.md')), false, 'the AIO source is named Render.gs, not a duplicate Code.gs markdown file');
assert.match(backend, /function doPost\(e\)/, 'the canonical backend remains in the parent folder');
assert.match(backend, /function doGet\(\)\s*\{\s*return json_\(\{ok:true,service:'apps-calendar',schemaVersion:3\}\);/);
assert.match(render, /function doGet\(\)/);
assert.match(render, /function runAgendaMaintenance\(/);
assert.match(render, /UrlFetchApp\.fetch/);
assert.match(render, /template\.apiUrl = AGENDA_BACKEND_URL/);
assert.match(render, /const AGENDA_BACKEND_URL = 'https:\/\/script\.google\.com\/macros\/s\/AKfycbwtfGNjudJ_TljvRZt5J5Q6rT86p3SaQ3j2gDSAd6VxiduMps2deyShYxoXxxmkFye1\/exec'/);
assert.doesNotMatch(render, /function doPost|SpreadsheetApp|CalendarApp|openById/);
assert.match(readme, /`Render\.gs`/);
assert.match(readme, /`\.\.\/Code\.gs`/);
assert.match(guide, /`Render\.gs`/);
assert.match(guide, /backend canónico/);
assert.match(guide, /No copiar el backend/);
assert.match(guide, /`script\.external_request`/);
assert.match(manifestDoc, /script\.external_request/);
const manifestMatch = manifestDoc.match(/```json\n([\s\S]*?)\n```/);
assert.ok(manifestMatch, 'complete AIO manifest exists');
const manifest = JSON.parse(manifestMatch[1]);
assert.deepEqual(manifest.oauthScopes, ['https://www.googleapis.com/auth/script.external_request']);
assert.doesNotMatch(manifestMatch[1], /calendar|spreadsheets/i);
const match = markdown.match(/```html\n([\s\S]*?)\n```/);
assert.ok(match, 'complete HTML code block exists');
const html = match[1];
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x => x[1]);
assert.match(html, /window\.APP_CONFIG = Object\.freeze\(\{ API_URL: <\?!= JSON\.stringify\(apiUrl\) \?>/);
assert.match(html, /window\.AGENDA_APPS_SCRIPT_STANDALONE = true/);
assert.equal(scripts.length, 4);
assert.match(html, /<style>[\s\S]*<\/style>/);
assert.doesNotMatch(html, /<script\s+src=|<link\s+rel="stylesheet"|<link\s+rel="manifest"|(?:src|href)="\.\.?\//);
assert.match(scripts[2], /atob\('/);
const embedded = scripts[2].match(/atob\('([A-Za-z0-9+/=]+)'\)/);
assert.ok(embedded, 'embedded Excel payload exists');
assert.deepEqual(Buffer.from(embedded[1], 'base64'), fs.readFileSync(path.join(dir, '..', '..', 'vendor', 'xlsx.full.min.js')), 'embedded Excel bytes match Pages asset');
assert.match(scripts[3], /window\.loadEmbeddedXlsx\(\)/);
assert.match(scripts[3], /if\(!window\.AGENDA_APPS_SCRIPT_STANDALONE&&'serviceWorker'in navigator\)/);
assert.match(scripts[3], /StageStore\.(?:replace|list)\('calendario'/);
assert.match(html, /Mantenimiento del Sheet/);
assert.match(html, /runAgendaMaintenance\(action/);
assert.match(html, /google\.script\.run/);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'agenda-standalone-'));
try {
  scripts.forEach((script, i) => {
    const code = i === 0 ? script.replace('<?!= JSON.stringify(apiUrl) ?>', JSON.stringify('https://example.test/exec')) : script;
    const file = path.join(tmp, `${i}.js`);
    fs.writeFileSync(file, code);
    execFileSync(process.execPath, ['--check', file], {stdio:'pipe'});
  });
  const renderFile = path.join(tmp, 'Render.js');
  fs.writeFileSync(renderFile, render);
  execFileSync(process.execPath, ['--check', renderFile], {stdio:'pipe'});
} finally { fs.rmSync(tmp, {recursive:true, force:true}); }
console.log('Agenda AIO Render.gs naming, canonical backend separation, assets and syntax PASS');
