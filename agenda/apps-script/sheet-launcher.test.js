'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const code = fs.readFileSync(path.join(__dirname, 'Code.gs'), 'utf8');
assert.ok(fs.existsSync(path.join(__dirname, 'aio', 'Render.gs')), 'AIO renderer source exists separately');
assert.equal(fs.existsSync(path.join(__dirname, 'aio', 'Code.gs.md')), false, 'no duplicate renderer named Code.gs');
assert.ok(fs.existsSync(path.join(__dirname, '..', 'agente', 'agent.md')), 'Agenda agent guide exists');
const menu = code.match(/function onOpen\(\)\s*\{([\s\S]*?)\n\}/);
assert.ok(menu, 'sheet open hook exists');
assert.ok(menu[1].includes(".createMenu('Agenda')"));
assert.ok(menu[1].includes(".addItem('Iniciar app', 'openAgendaAio')"));
for (const label of ['Verificar esquema normalizado', 'Actualizar tablas legibles', 'RESET total… (crea esquema normalizado)']) assert.ok(menu[1].includes(label), label);
const launcher = code.match(/function openAgendaAio\(\)\s*\{([\s\S]*?)\n\}/);
assert.ok(launcher, 'launcher function exists');
assert.ok(launcher[1].includes("getProperty('AGENDA_AIO_WEB_APP_URL')"));
assert.ok(launcher[1].includes('/(?:exec|dev)$/'));
assert.ok(launcher[1].includes("showModalDialog(html, 'Agenda')"));
assert.ok(launcher[1].includes('Iniciar app</a>'));
assert.match(code, /function doGet\(\)\s*\{\s*return json_\(\{ok:true,service:'apps-calendar',schemaVersion:3\}\);/);
assert.match(code, /function doPost\(e\)/);
assert.match(code, /function agendaDatabaseAction_\(action, body, username\)/);
assert.match(code, /AGENDA_AIO_WEB_APP_URL/);
console.log('Agenda normalized schema launcher contract PASS');
