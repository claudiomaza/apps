assert.doesNotMatch(app,/inputField\('documentNumber','Número de documento'/,'no redundant document number field is shown');
assert.match(css,/date-cell[\s\S]*min-width/,'date cells are given readable width');
assert.match(app,/\.documentNumber\|\|s\.data\.studentId/,'student tables show the DNI identifier');
assert.match(app,/function normalizeDni\([\s\S]*replace\(\/\\D\/g,''\)/,'normalization uses digits only without altering other data');
