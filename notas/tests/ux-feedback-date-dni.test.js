assert.equal((html.match(/id="sync-review-progress"/g)||[]).length,1,'there is one live progress line');
assert.match(app,/class="date-cell"/,'summary rows mark date columns for consistent width');
assert.match(app,/formatDateShort\(x\.date\)/,'summary chart dates use DD-MM-AA');
assert.match(app,/type==='student'\?String\(data\.studentId\|\|''\):uuid\(\)/,'student record IDs derive from the DNI');
console.log('Login toast, sync review, DNI and short-date regression contract PASS');
