
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../app.js'),'utf8');
const start=source.indexOf('function renderAvailability(){'),end=source.indexOf('\n',start);
assert(start>=0&&end>start,'availability renderer exists');
const values={'#scope-teacher':{value:'t1'},'#availability-teacher':{value:'',innerHTML:''},'#availability-selected-name':{textContent:''},'#availability-list':{innerHTML:''}};
const context={teachers:[{teacherId:'t1',name:'Docente Uno'},{teacherId:'t2',name:'Docente Dos'}],teacherAvailability:[{teacherId:'t1',availabilityId:'a',dayOfWeek:2,startTime:'14:00',endTime:'16:00'},{teacherId:'t2',availabilityId:'b',dayOfWeek:4,startTime:'08:00',endTime:'10:00'}],$:selector=>values[selector],esc:x=>String(x)};
vm.runInNewContext(source.slice(start,end),context);context.renderAvailability();
assert.equal(values['#availability-teacher'].value,'t1');
assert.equal(values['#availability-selected-name'].textContent,'Disponibilidad de Docente Uno · t1');
assert.match(values['#availability-list'].innerHTML,/martes 14:00–16:00/);
assert.doesNotMatch(values['#availability-list'].innerHTML,/jueves 08:00–10:00/,'do not mix another teacher availability');
assert.match(values['#availability-list'].innerHTML,/No puede tomar horas/);
values['#scope-teacher'].value='t2';context.renderAvailability();
assert.match(values['#availability-list'].innerHTML,/jueves 08:00–10:00/);
assert.doesNotMatch(values['#availability-list'].innerHTML,/martes 14:00–16:00/);
context.teacherAvailability=[];context.renderAvailability();
assert.match(values['#availability-list'].innerHTML,/Sin bloqueos: puede asignarse/);
console.log('Teacher availability card filtering and available-window UI PASS');
