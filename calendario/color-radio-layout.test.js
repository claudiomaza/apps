'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const css=fs.readFileSync(__dirname+'/styles.css','utf8');
const rule=css.match(/\.group-color-options input\s*\{([^}]*)\}/)?.[1]||'';
assert.match(rule,/width\s*:\s*16px/,'radio buttons must not inherit width:100% from the global input rule');
assert.match(rule,/padding\s*:\s*0/,'radio buttons must not inherit generic text-input padding');
assert.match(rule,/flex\s*:\s*0\s+0\s+16px/,'radios must retain a compact fixed size within flex labels');
assert.match(css,/\.group-color-options label\{min-width:0;overflow-wrap:normal\}/,'color names must wrap at words, not mid-word');
assert.match(css,/\.group-color-options label\{display:flex;align-items:center;gap:5px;padding:8px 6px/,'compact labels preserve space for color names');
console.log('Group-color radio layout contract PASS');
