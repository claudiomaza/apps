'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync(__dirname+'/index.html','utf8'),app=fs.readFileSync(__dirname+'/app.js','utf8');
const login=html.match(/<form\b[^>]*id="login-panel"[\s\S]*?<\/form>/)?.[0]||'';
assert.ok(login,'login must be a native form');
assert.match(login,/<input\b[^>]*id="access-user"[^>]*required/);
assert.match(login,/<input\b[^>]*id="access-pass"[^>]*required/);
assert.match(login,/<button\b[^>]*id="login-button"[^>]*type="submit"/);
assert.match(app,/\$\('#login-panel'\)\.addEventListener\('submit',\s*\w+\s*=>\s*\{\s*\w+\.preventDefault\(\);\s*if\(!\$\('#login-panel'\)\.reportValidity\(\)\)return;\s*authenticate\(\);\s*\}\)/);
assert.doesNotMatch(app,/\$\('#login-button'\)\.onclick\s*=\s*authenticate/);
assert.doesNotMatch(app,/\$\('#access-pass'\)\.addEventListener\('keydown'/);
console.log('Login form validation contract PASS');
