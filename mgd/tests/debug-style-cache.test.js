'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const config=fs.readFileSync(path.join(root,'config.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.match(config,/ASSET_CACHE_ENABLED:\s*false/,'asset cache stays off by default during debugging');
assert.match(config,/SERVICE_WORKER_ENABLED:\s*false/,'service worker stays off by default during debugging');
assert.match(html,/SERVICE_WORKER_ENABLED===true[\s\S]*?register\(/,'service worker registration is controlled by config');
assert.match(html,/cfg\.ASSET_CACHE_ENABLED===true\?'1':'0'/,'worker cache mode follows explicit config flag');assert.match(html,/cfg\.ASSET_CACHE_ENABLED===true\?null:caches\.keys\(\)/,'debug mode clears only app-owned asset caches');
assert.match(sw,/searchParams\.get\('cache'\)==='1'/,'service worker cache behavior follows explicit config flag');
assert.match(css,/\.login-panel h1\{[^}]*font-size:clamp\(1\.65rem,5vw,2\.35rem\)/,'login heading is deliberately compact');
assert.match(css,/\.toast\{[^}]*background:#20342c!important;[^}]*color:#fff!important/,'toast stays dark with readable text in either theme');
assert(css.includes('body.theme-dark .toast,body.theme-dark .toast[data-state=success],body.theme-dark .toast[data-state=loading]{background:#20342c!important;color:#fff!important}'),'dark theme cannot invert the toast into a white box');
assert.match(css,/\.toast-spinner\{[^}]*border-radius:50%/,'loading indicator remains a separate circular spinner');
console.log('Debug cache configuration + login/toast regression contract PASS');
